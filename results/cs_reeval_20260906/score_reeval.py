"""Score every (model, controlnet_conditioning_scale) cell produced by
experiments/run_cs_reeval_20260906.sh.

The cs=1.0 column should reproduce results/ten_model_comparison/metrics.csv,
since it is generated by the same infer script with the same arguments the
historical evals used. That comparison is printed as an anchor check: a
mismatch means this sweep's model->checkpoint/conditioning/caption mapping
is wrong, and nothing else in the table should be trusted until it is
fixed.

Axes follow the 2026-09-05 correction (inbox/initial_notice.md 運用ルール):
orientation_entropy alone cannot separate a hatch mesh from the smooth
boundary of a solid fill, so line_width_p50 (GT ~3.72) and ink_ratio
(GT ~0.0353) are always reported with it.
"""

import csv
import sys
from pathlib import Path

import numpy as np
from PIL import Image

sys.path.insert(0, "/home/sh1/deepl/lineart/tools/evaluation")
sys.path.insert(0, "/home/sh1/deepl/lineart/tools/pair_extraction")
from measure_lineart_profile import profile_metrics  # noqa: E402
from tile_region_manifest_480 import edge_map, bipartite_match_f1  # noqa: E402

TRACK = Path("/home/sh1/deepl/lineart-controlnet-realpairs")
SAMPLES = [l.strip()[:-4] for l in open(TRACK / "data/diag_valid5.txt") if l.strip()]
OUT_ROOT = TRACK / "results/cs_reeval_20260906/outputs"
IMAGE_SIZE = 480
BSDS_TOLERANCE_PX = 2.0
PROFILE_AXES = ["orientation_entropy", "line_width_p50", "ink_ratio", "components_per_1k_ink_px"]
COLS = ["gt_bsds_f1", "precision", "recall"] + PROFILE_AXES

# gt_bsds_f1 at cs=1.0 from results/ten_model_comparison/metrics.csv, for the
# anchor check. manga_unetlora_trained postdates that table, so it has none.
HISTORICAL_F1 = {
    "anime_trained": 0.1476,
    "coarse_trained": 0.1538,
    "sd15_lineart_trained": 0.1558,
    "manga_trained": 0.1293,
    "manga_rank32_trained": 0.1411,
    "manga_epoch2_trained": 0.1297,
    "manga_consistency_trained": 0.1411,
    "manga_nomangaword_trained": 0.1417,
    "sdxl_trained": 0.0945,
    "sdxl_manga_trained": 0.1226,
}


def load_gray_array(path):
    return np.asarray(Image.open(path).convert("L").resize((IMAGE_SIZE, IMAGE_SIZE)))


def score_dir(out_dir):
    vals = {a: [] for a in PROFILE_AXES}
    f1s, precisions, recalls = [], [], []
    for s in SAMPLES:
        p = out_dir / f"{s}_out.png"
        m = profile_metrics(p)
        for a in PROFILE_AXES:
            vals[a].append(m[a])
        gt_edge = edge_map(load_gray_array(TRACK / f"data/diag_gt_line_{s}.jpg"))
        f1, precision, recall = bipartite_match_f1(
            edge_map(load_gray_array(p)), gt_edge, BSDS_TOLERANCE_PX
        )
        f1s.append(f1)
        precisions.append(precision)
        recalls.append(recall)
    out = {a: float(np.mean(vals[a])) for a in PROFILE_AXES}
    out["gt_bsds_f1"] = float(np.mean(f1s))
    out["precision"] = float(np.mean(precisions))
    out["recall"] = float(np.mean(recalls))
    return out


def gt_reference():
    vals = {a: [] for a in PROFILE_AXES}
    for s in SAMPLES:
        m = profile_metrics(TRACK / f"data/diag_gt_line_{s}.jpg")
        for a in PROFILE_AXES:
            vals[a].append(m[a])
    return {a: float(np.mean(vals[a])) for a in PROFILE_AXES}


def main():
    models = sorted(d.name for d in OUT_ROOT.iterdir() if d.is_dir())
    rows = []
    for model in models:
        for cs_dir in sorted((OUT_ROOT / model).iterdir(), key=lambda d: float(d.name[2:])):
            if not (cs_dir / ".complete").exists():
                print(f"(skipping incomplete cell: {model} {cs_dir.name})", file=sys.stderr)
                continue
            rows.append({"model": model, "cs": float(cs_dir.name[2:]), **score_dir(cs_dir)})

    gt = gt_reference()
    out_csv = TRACK / "results/cs_reeval_20260906/scores.csv"
    with open(out_csv, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["model", "cs"] + COLS)
        w.writeheader()
        w.writerow({"model": "GT(reference)", "cs": "", **{a: round(gt[a], 4) for a in PROFILE_AXES}})
        for r in rows:
            w.writerow({k: (round(v, 4) if isinstance(v, float) else v) for k, v in r.items()})

    print("=== anchor check: cs=1.0 gt_bsds_f1 vs results/ten_model_comparison/metrics.csv ===")
    print(f"{'model':28}{'now':>10}{'historical':>13}{'delta':>10}")
    worst = 0.0
    for r in [r for r in rows if r["cs"] == 1.0]:
        hist = HISTORICAL_F1.get(r["model"])
        if hist is None:
            print(f"{r['model']:28}{r['gt_bsds_f1']:10.4f}{'(new model)':>13}")
            continue
        delta = r["gt_bsds_f1"] - hist
        worst = max(worst, abs(delta))
        print(f"{r['model']:28}{r['gt_bsds_f1']:10.4f}{hist:13.4f}{delta:+10.4f}")
    verdict = "OK" if worst < 0.005 else "MISMATCH -- check model->checkpoint/conditioning/caption mapping"
    print(f"max |delta| = {worst:.4f}  -> {verdict}")

    print(f"\n=== gt_bsds_f1 by model x cs (GT ink_ratio {gt['ink_ratio']:.4f}, line_width_p50 {gt['line_width_p50']:.2f}) ===")
    scales = sorted({r["cs"] for r in rows})
    print(f"{'model':28}" + "".join(f"{f'cs{c}':>10}" for c in scales) + f"{'best':>12}")
    for model in models:
        by_cs = {r["cs"]: r for r in rows if r["model"] == model}
        if not by_cs:
            continue
        best_cs = max(by_cs, key=lambda c: by_cs[c]["gt_bsds_f1"])
        line = f"{model:28}"
        for c in scales:
            line += f"{by_cs[c]['gt_bsds_f1']:10.4f}" if c in by_cs else f"{'-':>10}"
        line += f"{f'cs{best_cs}':>12}"
        print(line)

    print("\n=== each model at its best cs (full axes) ===")
    print(f"{'model':28}{'cs':>6}{'f1':>9}{'ink_ratio':>11}{'line_w_p50':>12}{'orient_ent':>12}")
    best_rows = []
    for model in models:
        by_cs = [r for r in rows if r["model"] == model]
        if not by_cs:
            continue
        best = max(by_cs, key=lambda r: r["gt_bsds_f1"])
        best_rows.append(best)
    for r in sorted(best_rows, key=lambda r: -r["gt_bsds_f1"]):
        print(
            f"{r['model']:28}{r['cs']:6.1f}{r['gt_bsds_f1']:9.4f}{r['ink_ratio']:11.4f}"
            f"{r['line_width_p50']:12.2f}{r['orientation_entropy']:12.4f}"
        )
    print(f"{'GT(reference)':28}{'':6}{'':9}{gt['ink_ratio']:11.4f}{gt['line_width_p50']:12.2f}{gt['orientation_entropy']:12.4f}")

    print(f"\nsaved: {out_csv}")


if __name__ == "__main__":
    main()
