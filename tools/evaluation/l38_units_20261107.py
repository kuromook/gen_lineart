def split(rows, key=lambda r: r['area']):
    """`(面, 小片)` に分ける。**どちらも返す** —— 落とした側を黙って捨てない(規律9)。"""
    face = [r for r in rows if key(r) >= FRAGMENT_FLOOR]
    frag = [r for r in rows if key(r) < FRAGMENT_FLOOR]
    return face, frag


def line(name, rows, key=lambda r: r['area']):
    f, g = split(rows, key)
    n = len(rows)
    return (f'{name}: **前 {n}** -> **面 {len(f)}** / 小片 {len(g)}'
            + (f'({len(g) / n:.1%})' if n else ''))
