"""L38 **単位の定義**(2026-11-07、作者の裁定で登録)。

> **面とも線ともつかない単位をつくるべきだろう　小さすぎるものは**(作者、2026-11-07)

- **面** —— 塗り層の和(`fill_mask(radius=4)`)の8連結成分 ∩ コマ成分で、**面積 >= 6,000 画素**
- **小片** —— 同じ作りで **面積 < 6,000 画素**。**捨てない。別プールにして数を印字する**
  (`done*` と同じ扱い。欠けの向きが既知のものは、1行に混ぜないだけで材料としては残る)

**床 6,000 の出所**: これまでの裁定302面の統計(`l38_fragment_floor_20261107.py`)——
ブートストラップ400回の**中央 5,868**、Youden 最良 8,212、並べ替え検定 p=0.004。
**作者が 6,000 を選んだ**(2026-11-07)。

**引き直す時期と条件(先に書く。規律10)**:

1. **裁定の在る面が 500 に達したら引き直す**(いまは 302)
2. **作者が単位の定義を変えたとき**(規律6: 単位は作者のもの)
3. 引き直したら **前後の床と、前後の数を両方、名前を付けて印字する**。
   **過去の結果は撤回しない** —— 床の版は構成の一部である(規律1)

**小片は「分からない」ではない。** 床の上でも「答えられなかった」面は 7.1% 残る。
"""
FRAGMENT_FLOOR = 6000
FLOOR_REGISTERED = '2026-11-07'


def split(rows, key=lambda r: r['area']):
    """`(面, 小片)` に分ける。**どちらも返す** —— 落とした側を黙って捨てない(規律9)。"""
    face = [r for r in rows if key(r) >= FRAGMENT_FLOOR]
    frag = [r for r in rows if key(r) < FRAGMENT_FLOOR]
    return face, frag


def line(name, rows, key=lambda r: r['area']):
    f, g = split(rows, key)
    n = len(rows)
    return (f'{name}: **前 {n}** -> **面 {len(f)}** / 小片 {len(g)}'
            + (f'({len(g) / n:.1%})' if n else ''))
