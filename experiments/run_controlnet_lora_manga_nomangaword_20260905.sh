#!/bin/bash
# Hypothesis #5 (inbox/initial_notice.md, 2026-09-05): after hypotheses #1
# (data-pool bias), #2 (LoRA rank capacity), #3 (epoch count), and #4
# (x0-vs-GT consistency loss) were all measured and rejected, this tests
# whether the base SD1.5 model's pretrained prior for the word "manga"
# (strongly associated with hatching/screentone shading on the open web,
# per literature review -- ControlNet++/InnerControl document the general
# condition-fidelity gap, and community writeups note manga-as-a-concept
# implies hatched/toned shading) is dominating over the LoRA's correction
# whenever the caption contains "manga panel".
#
# A same-checkpoint, inference-caption-only ablation on 2026-09-05
# (results/caption_ablation_20260905/) was inconclusive/negative, but it
# was confounded: the manga_trained LoRA weights were themselves trained
# on captions that always included "manga panel", so swapping only the
# inference caption doesn't fairly test this. This script removes "manga
# panel" from *training* captions too (data/captions_no_manga_word.csv,
# generated by stripping the uniform ", manga panel" suffix present in
# all 8467 rows of data/captions.csv -- verified before this script was
# written) and retrains from scratch, otherwise identical to manga_trained
# (controlnet_lora_manga_20260827: same base_ckpt/ControlNet-init/rough-
# preprocessing/rank16/epochs10/lr) so this isolates the one variable:
# the caption's "manga panel" phrase.
set -euo pipefail
cd "$(dirname "$0")/.."

PY=/home/sh1/deepl/lineart/venv/bin/python
TAG=controlnet_lora_manga_nomangaword_20260905
EPOCHS=${EPOCHS:-10}
LORA_RANK=${LORA_RANK:-16}
LR=${LR:-1e-4}
FILE_LIST=data/train_list.txt
ROUGH_DIR=data/rough_manga_line
LINE_DIR=data/line
CAPTION_CSV=data/captions_no_manga_word.csv
BASE_CKPT=$HOME/disk/checkpoint/Stable-diffusion/v1-5-pruned-emaonly.safetensors
CONTROLNET_INIT=$HOME/disk/checkpoint/ControlNet/control_v11p_sd15s2_lineart_anime

LOG=logs/${TAG}.log
DONE=logs/${TAG}.done
CKPT=checkpoints/${TAG}

mkdir -p logs checkpoints

WRITTEN=$(find "$ROUGH_DIR" -type f 2>/dev/null | wc -l)
EXPECTED=$(wc -l < "$FILE_LIST")
if [ "$WRITTEN" -ne "$EXPECTED" ]; then
  echo "ERROR: $ROUGH_DIR has $WRITTEN files, expected $EXPECTED -- preprocessing incomplete, refusing to train" >&2
  exit 1
fi

CAPTION_ROWS=$(wc -l < "$CAPTION_CSV")
if [ "$CAPTION_ROWS" -ne 8468 ]; then
  echo "ERROR: $CAPTION_CSV has $CAPTION_ROWS lines, expected 8468 (8467 rows + header) -- refusing to train" >&2
  exit 1
fi

: > "$LOG"
exec > >(tee -a "$LOG") 2>&1

echo "[$(date --iso-8601=seconds)] controlnet LoRA (manga_line preprocessing, 'manga panel' removed from captions) fine-tune start (epochs=$EPOCHS rank=$LORA_RANK lr=$LR)"
echo "file count: $(wc -l < "$FILE_LIST")"
echo "caption_csv: $CAPTION_CSV (manga panel stripped)"

echo "=== smoke test (6 steps, scratch dir) ==="
SMOKE_CKPT=checkpoints/${TAG}_smoke
rm -rf "$SMOKE_CKPT"
"$PY" /home/sh1/deepl/lineart/scripts/train_controlnet.py \
  --file-list "$FILE_LIST" \
  --rough-dir "$ROUGH_DIR" \
  --line-dir "$LINE_DIR" \
  --base-ckpt "$BASE_CKPT" \
  --controlnet-init "$CONTROLNET_INIT" \
  --controlnet-lora-rank "$LORA_RANK" \
  --caption-csv "$CAPTION_CSV" \
  --output-dir "$SMOKE_CKPT" \
  --max-train-steps 6 \
  --log-steps 1
echo "smoke test passed, cleaning up scratch checkpoint"
rm -rf "$SMOKE_CKPT"

echo "=== full fine-tune ($EPOCHS epochs) ==="
"$PY" /home/sh1/deepl/lineart/scripts/train_controlnet.py \
  --file-list "$FILE_LIST" \
  --rough-dir "$ROUGH_DIR" \
  --line-dir "$LINE_DIR" \
  --base-ckpt "$BASE_CKPT" \
  --controlnet-init "$CONTROLNET_INIT" \
  --controlnet-lora-rank "$LORA_RANK" \
  --caption-csv "$CAPTION_CSV" \
  --output-dir "$CKPT" \
  --epochs "$EPOCHS" \
  --lr "$LR" \
  --save-steps 500 \
  --log-steps 50

echo "=== eval (diag5, condition matching training format, 'manga panel'-free caption) ==="
"$PY" /home/sh1/deepl/lineart/scripts/infer_controlnet.py \
  --sample-list data/diag_valid5.txt \
  --rough-dir data/diag_rough_manga_line \
  --controlnet-dir "$CONTROLNET_INIT" \
  --controlnet-lora-dir "$CKPT/final" \
  --base-ckpt "$BASE_CKPT" \
  --caption "monochrome line art, clean linework, black and white" \
  --tag "${TAG}_eval" \
  --output-dir "results/${TAG}_eval"

rm -rf "$CKPT/resume_state"
echo "removed resume_state (no longer needed after successful completion)"

{
  echo "completed_at=$(date --iso-8601=seconds)"
  echo "tag=$TAG"
  echo "epochs=$EPOCHS"
  echo "lora_rank=$LORA_RANK"
  echo "lr=$LR"
  echo "file_list=$FILE_LIST"
  echo "rough_dir=$ROUGH_DIR"
  echo "line_dir=$LINE_DIR"
  echo "caption_csv=$CAPTION_CSV"
  echo "controlnet_init=$CONTROLNET_INIT"
  echo "checkpoint=$CKPT/final"
  echo "eval_dir=results/${TAG}_eval"
} > "$DONE"

/home/sh1/deepl/lineart/experiments/send_autoloop_notification.sh \
  "ControlNet LoRA (manga_line preprocessing, 'manga panel' removed from captions) fine-tune complete" \
  "Review results/${TAG}_eval/" || true

echo "done marker: $DONE"
echo "[$(date --iso-8601=seconds)] controlnet LoRA (manga_line preprocessing, 'manga panel' removed from captions) fine-tune complete"
