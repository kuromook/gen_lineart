#!/bin/bash
# Re-run of controlnet_lora_realpairs_20260824, swapping the conditioning
# preprocessor from `lineart_anime` to `lineart_coarse` (LineartDetector,
# coarse=True). Motivation: inbox/initial_notice.md 2026-08-26 entry --
# `lineart_anime` (trained to extract lines from finished/colored anime art)
# discards ~50% of a rough sketch's visible ink; `lineart_coarse` (derived
# from the Simo-Serra et al. rough-sketch-cleanup network) retains ~170% by
# the same measure and visually tracks the raw rough much more closely,
# including faint construction lines the anime detector missed entirely.
# Conditioning images pre-generated by
# tools/preprocess_lineart_coarse_condition.py into data/rough_lineart_coarse/
# (8467/8467 written, no errors, run took ~11min -- see
# logs/preprocess_lineart_coarse_20260826.log). Everything else (data,
# rank, lr, epochs, caption) held fixed vs the 20260824 run so this isolates
# the one variable being tested, per project convention.
set -euo pipefail
cd "$(dirname "$0")/.."

PY=/home/sh1/deepl/lineart/venv/bin/python
TAG=controlnet_lora_coarse_20260827
EPOCHS=${EPOCHS:-10}
LORA_RANK=${LORA_RANK:-16}
LR=${LR:-1e-4}
FILE_LIST=data/train_list.txt
ROUGH_DIR=data/rough_lineart_coarse
LINE_DIR=data/line
CAPTION_CSV=data/captions.csv
BASE_CKPT=$HOME/disk/checkpoint/Stable-diffusion/v1-5-pruned-emaonly.safetensors
CONTROLNET_INIT=$HOME/disk/checkpoint/ControlNet/control_v11p_sd15s2_lineart_anime

LOG=logs/${TAG}.log
DONE=logs/${TAG}.done
CKPT=checkpoints/${TAG}

mkdir -p logs checkpoints
: > "$LOG"
exec > >(tee -a "$LOG") 2>&1

echo "[$(date --iso-8601=seconds)] controlnet LoRA coarse-preprocessed fine-tune start (epochs=$EPOCHS rank=$LORA_RANK lr=$LR)"
echo "file count: $(wc -l < "$FILE_LIST")"

echo "=== smoke test (6 steps, scratch dir) already verified interactively 2026-08-26, skipping re-run ==="

echo "=== full fine-tune ($EPOCHS epochs) ==="
"$PY" /home/sh1/deepl/lineart/scripts/train_controlnet.py \
  --file-list "$FILE_LIST" \
  --rough-dir "$ROUGH_DIR" \
  --line-dir "$LINE_DIR" \
  --base-ckpt "$BASE_CKPT" \
  --controlnet-init "$CONTROLNET_INIT" \
  --controlnet-lora-rank "$LORA_RANK" \
  --caption-csv "$CAPTION_CSV" \
  --output-dir "$CKPT" \
  --epochs "$EPOCHS" \
  --lr "$LR" \
  --save-steps 500 \
  --log-steps 50

echo "=== eval (diag5, preprocessed condition matching training format) ==="
"$PY" /home/sh1/deepl/lineart/scripts/infer_controlnet.py \
  --sample-list data/diag_valid5.txt \
  --rough-dir data/diag_rough_lineart_coarse \
  --controlnet-dir "$CONTROLNET_INIT" \
  --controlnet-lora-dir "$CKPT/final" \
  --base-ckpt "$BASE_CKPT" \
  --caption "monochrome line art, manga panel, black and white" \
  --tag "${TAG}_eval" \
  --output-dir "results/${TAG}_eval"

{
  echo "completed_at=$(date --iso-8601=seconds)"
  echo "tag=$TAG"
  echo "epochs=$EPOCHS"
  echo "lora_rank=$LORA_RANK"
  echo "lr=$LR"
  echo "file_list=$FILE_LIST"
  echo "rough_dir=$ROUGH_DIR"
  echo "line_dir=$LINE_DIR"
  echo "caption_csv=$CAPTION_CSV"
  echo "controlnet_init=$CONTROLNET_INIT"
  echo "checkpoint=$CKPT/final"
  echo "eval_dir=results/${TAG}_eval"
} > "$DONE"

echo "done marker: $DONE"
echo "[$(date --iso-8601=seconds)] controlnet LoRA coarse-preprocessed fine-tune complete"
