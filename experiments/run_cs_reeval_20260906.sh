#!/bin/bash
# Re-evaluate every trained model in this track across a ladder of
# controlnet_conditioning_scale values (inbox/initial_notice.md,
# 2026-09-05/06).
#
# Why: the 2026-09-05 inference-only sweep found cs -- not data, LoRA rank,
# epochs, loss shape, or caption vocabulary -- to be what drives the
# cross-hatch hallucination (gt_bsds_f1 0.1411 -> 0.2337 on
# manga_consistency just by moving cs 1.0 -> 3.5). But every model
# comparison in this track to date was run at cs=1.0, the region where the
# hallucination dominates and all ten models sat bunched at f1 0.13-0.15.
# Hypotheses #1-#5 were all rejected on that bunched evidence. This
# re-measures them at the useful operating point to see whether the ranking
# changes -- if it does, those rejections were made in a regime where the
# effect they were looking for was masked.
#
# Deliberately calls the same infer_controlnet.py / infer_controlnet_sdxl.py
# entry points every historical eval used, once per (model, scale), rather
# than reimplementing a shared pipeline loop. That costs ~15s of model
# reload per cell (~14 min total, irrelevant for an unattended run) and buys
# the thing that makes this experiment meaningful: the cs=1.0 column is
# generated by the exact code path that produced the historical numbers, so
# it doubles as an anchor check against
# results/ten_model_comparison/metrics.csv.
set -euo pipefail
cd "$(dirname "$0")/.."

PY=/home/sh1/deepl/lineart/venv/bin/python
SD15_INFER=/home/sh1/deepl/lineart/scripts/infer_controlnet.py
SDXL_INFER=scripts/infer_controlnet_sdxl.py

SD15_BASE=$HOME/disk/checkpoint/Stable-diffusion/v1-5-pruned-emaonly.safetensors
SDXL_BASE=/home/sh1/.cache/huggingface/hub/models--cagliostrolab--animagine-xl-3.1/snapshots/483f0c322568ed13697ed01dd0be07204746d12b
CN_ANIME=$HOME/disk/checkpoint/ControlNet/control_v11p_sd15s2_lineart_anime
CN_SD15_LINEART=$HOME/disk/checkpoint/ControlNet/control_v11p_sd15_lineart
CN_SDXL_ANIME=/home/sh1/.cache/huggingface/hub/models--Eugeoter--noob-sdxl-controlnet-lineart_anime/snapshots/61ed2d40710b32a5a1c9873f7dec89ff0af9f2a4
CN_SDXL_MANGA=/home/sh1/.cache/huggingface/hub/models--Eugeoter--noob-sdxl-controlnet-manga_line/snapshots/bc7619904de6489ba7e171cf27a80f0e12822943

CAPTION_DEFAULT="monochrome line art, manga panel, black and white"
# nomangaword was trained with "manga panel" stripped from all 8467 captions,
# so it is evaluated on the caption distribution it actually saw.
CAPTION_NOMANGA="monochrome line art, clean linework, black and white"

SCALES=${SCALES:-"1.0 2.0 2.5 3.0 3.5"}
OUT_ROOT=results/cs_reeval_20260906
LOG=logs/cs_reeval_20260906.log
DONE=logs/cs_reeval_20260906.done

# label | arch | checkpoint | controlnet_init | rough_dir | caption
MODELS=(
  "anime_trained|sd15|checkpoints/controlnet_lora_realpairs_20260824|$CN_ANIME|data/diag_rough_lineart_anime|$CAPTION_DEFAULT"
  "coarse_trained|sd15|checkpoints/controlnet_lora_coarse_20260827|$CN_ANIME|data/diag_rough_lineart_coarse|$CAPTION_DEFAULT"
  "sd15_lineart_trained|sd15|checkpoints/controlnet_lora_lineartsd15_20260827|$CN_SD15_LINEART|data/diag_rough_lineart_coarse|$CAPTION_DEFAULT"
  "manga_trained|sd15|checkpoints/controlnet_lora_manga_20260827|$CN_ANIME|data/diag_rough_manga_line|$CAPTION_DEFAULT"
  "manga_rank32_trained|sd15|checkpoints/controlnet_lora_manga_rank32_20260902|$CN_ANIME|data/diag_rough_manga_line|$CAPTION_DEFAULT"
  "manga_epoch2_trained|sd15|checkpoints/controlnet_lora_manga_epoch2_20260903|$CN_ANIME|data/diag_rough_manga_line|$CAPTION_DEFAULT"
  "manga_consistency_trained|sd15|checkpoints/controlnet_lora_manga_consistency_20260904|$CN_ANIME|data/diag_rough_manga_line|$CAPTION_DEFAULT"
  "manga_nomangaword_trained|sd15|checkpoints/controlnet_lora_manga_nomangaword_20260905|$CN_ANIME|data/diag_rough_manga_line|$CAPTION_NOMANGA"
  "manga_unetlora_trained|sd15_unetlora|checkpoints/controlnet_lora_manga_unetlora_20260905|$CN_ANIME|data/diag_rough_manga_line|$CAPTION_DEFAULT"
  "sdxl_trained|sdxl|checkpoints/controlnet_lora_sdxl_20260829|$CN_SDXL_ANIME|data/diag_rough_lineart_coarse|$CAPTION_DEFAULT"
  "sdxl_manga_trained|sdxl|checkpoints/controlnet_lora_sdxl_manga_20260830|$CN_SDXL_MANGA|data/diag_rough_manga_line|$CAPTION_DEFAULT"
)

mkdir -p logs "$OUT_ROOT"
: > "$LOG"
exec > >(tee -a "$LOG") 2>&1

echo "[$(date --iso-8601=seconds)] cs re-eval start: ${#MODELS[@]} models x scales [$SCALES]"

for entry in "${MODELS[@]}"; do
  IFS='|' read -r LABEL ARCH CKPT CN_INIT ROUGH_DIR CAPTION <<< "$entry"

  if [ ! -f "$CKPT/final/pytorch_lora_weights.safetensors" ]; then
    echo "WARNING: $LABEL has no $CKPT/final/pytorch_lora_weights.safetensors -- skipping" >&2
    continue
  fi

  for CS in $SCALES; do
    OUT_DIR="$OUT_ROOT/outputs/${LABEL}/cs${CS}"
    if [ -f "$OUT_DIR/.complete" ]; then
      echo "--- $LABEL cs=$CS already done, skipping"
      continue
    fi
    echo "--- $LABEL (arch=$ARCH) cs=$CS -> $OUT_DIR"
    mkdir -p "$OUT_DIR"

    case "$ARCH" in
      sd15)
        "$PY" "$SD15_INFER" \
          --sample-list data/diag_valid5.txt --rough-dir "$ROUGH_DIR" \
          --controlnet-dir "$CN_INIT" --controlnet-lora-dir "$CKPT/final" \
          --base-ckpt "$SD15_BASE" --caption "$CAPTION" \
          --controlnet-conditioning-scale "$CS" \
          --tag "cs_reeval_${LABEL}_cs${CS}" --output-dir "$OUT_DIR"
        ;;
      sd15_unetlora)
        # hypothesis #6 model: ControlNet LoRA + a second LoRA on the UNet
        "$PY" "$SD15_INFER" \
          --sample-list data/diag_valid5.txt --rough-dir "$ROUGH_DIR" \
          --controlnet-dir "$CN_INIT" --controlnet-lora-dir "$CKPT/final" \
          --lora-dir "$CKPT/final/unet_lora" \
          --base-ckpt "$SD15_BASE" --caption "$CAPTION" \
          --controlnet-conditioning-scale "$CS" \
          --tag "cs_reeval_${LABEL}_cs${CS}" --output-dir "$OUT_DIR"
        ;;
      sdxl)
        "$PY" "$SDXL_INFER" \
          --sample-list data/diag_valid5.txt --rough-dir "$ROUGH_DIR" \
          --controlnet-dir "$CN_INIT" --controlnet-lora-dir "$CKPT/final" \
          --base-ckpt "$SDXL_BASE" --caption "$CAPTION" \
          --controlnet-conditioning-scale "$CS" \
          --tag "cs_reeval_${LABEL}_cs${CS}" --output-dir "$OUT_DIR"
        ;;
      *)
        echo "ERROR: unknown arch $ARCH for $LABEL" >&2; exit 1 ;;
    esac
    touch "$OUT_DIR/.complete"
  done
done

echo "=== scoring ==="
"$PY" "$OUT_ROOT/score_reeval.py"

echo "=== montages ==="
"$PY" "$OUT_ROOT/make_montage.py"

{
  echo "completed_at=$(date --iso-8601=seconds)"
  echo "scales=$SCALES"
  echo "models=${#MODELS[@]}"
  echo "output_dir=$OUT_ROOT"
} > "$DONE"

/home/sh1/deepl/lineart/experiments/send_autoloop_notification.sh \
  "cs re-evaluation of all models complete" \
  "Review $OUT_ROOT/scores.csv and montages" || true

echo "[$(date --iso-8601=seconds)] cs re-eval complete"
